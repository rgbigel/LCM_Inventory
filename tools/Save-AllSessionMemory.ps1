<#
.SYNOPSIS
  "Save all": writes the session memory files and nothing else (no commit, no push).
.DESCRIPTION
  Module: tools/Save-AllSessionMemory.ps1
  Purpose: Session memory is saved in two places under LCM_AI\.agents:
           1. ACTIVE_CONTEXT.md   - the "Last Updated" stamp and an auto-generated
                                    "Session Snapshot" block (repo, branch, HEAD, state).
           2. LEARNED_ADVICE.md   - gets the lines passed via -Learn appended as candidates (dated,
                                    duplicates skipped, existing lines never rewritten).
           The narrative parts of ACTIVE_CONTEXT.md are written by the agent, not by this script.
  Path: LCM_Inventory/tools/Save-AllSessionMemory.ps1
  Authors: Rolf, LCM_AI Engine
  Version: 10.2.1
  Date: 2026-11-10
  Rule: RULE-PS-001 - RULE-PS-021, RULE-LCM-030
.PARAMETER Learn
  New lines for LEARNED_ADVICE.md; they enter as candidates (/learn) and need a review.
.PARAMETER Quiescent
  Record session status as Quiescent in ACTIVE_SESSION.md.
.PARAMETER DryRun
  Report what would be written, change nothing.
#>

[CmdletBinding()]
param(
    [string[]]$Learn = @(),
    [string]$Author = 'AI',
    [switch]$Quiescent,
    [switch]$DryRun,
    [Alias('h', '?')]
    [switch]$Help
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

if ($Help) {
    Write-Host 'Save-AllSessionMemory.ps1 [-Learn <string[]>] [-Author <name>] [-DryRun] [-h]'
    Write-Host '  Updates ACTIVE_CONTEXT.md (stamp + Session Snapshot) and adds -Learn lines as candidates to LEARNED_ADVICE.md.'
    Write-Host '  Never commits or pushes.'
    return
}

$contextModule = Join-Path (Split-Path $PSScriptRoot -Parent) 'modules\LCM_Context.psm1'
Import-Module -Name $contextModule -Force
$gitRoot = Get-LcmMachineGitRoot
$agentsDir = Join-Path $gitRoot 'LCM_AI\.agents'
$contextFile = Join-Path $agentsDir 'ACTIVE_CONTEXT.md'
$today = Get-Date -Format 'yyyy-MM-dd'
$stamp = Get-Date -Format 'yyyy-MM-dd HH:mm:ss'
$utf8 = [System.Text.UTF8Encoding]::new($false)

# --- Session Snapshot ---------------------------------------------------------
$rows = [System.Collections.Generic.List[string]]::new()
$repoDirs = @($gitRoot) + @(Get-ChildItem -LiteralPath $gitRoot -Directory -Force | Where-Object { $_.Name -notlike '.*' } | ForEach-Object { $_.FullName })
foreach ($dir in $repoDirs) {
    if (-not (Test-Path -LiteralPath (Join-Path $dir '.git'))) { continue }
    $name = if ($dir -eq $gitRoot) { 'Git_Repositories' } else { Split-Path $dir -Leaf }
    $branch = (git -C $dir rev-parse --abbrev-ref HEAD 2>$null)
    $head = (git -C $dir rev-parse --short HEAD 2>$null)
    if (-not $head) { $head = 'none' }
    $dirty = @(git -C $dir status --short 2>$null).Count
    $ahead = (git -C $dir rev-list --count '@{u}..HEAD' 2>$null)
    if ($LASTEXITCODE -ne 0) { $ahead = 'no upstream' }
    $state = if ($dirty -gt 0) { "uncommitted: $dirty" } elseif ($ahead -eq 'no upstream') { 'committed, no upstream' } elseif ([int]$ahead -gt 0) { "committed, unpublished: $ahead" } else { 'published' }
    $rows.Add("| $name | $branch | $head | $state |")
}

$snapshot = @(
    '<!-- SESSION_SNAPSHOT:BEGIN (generated by Save-AllSessionMemory.ps1; do not edit) -->'
    '## Session Snapshot'
    ''
    "Saved: $stamp"
    ''
    '| Repository | Branch | HEAD | State |'
    '|---|---|---|---|'
) + $rows + @('<!-- SESSION_SNAPSHOT:END -->')
$snapshotText = ($snapshot -join "`r`n")

$ctx = [System.IO.File]::ReadAllText($contextFile)
$ctx = [regex]::Replace($ctx, '(?m)^\*\*Last Updated:\*\* .*?(\s*)$', "**Last Updated:** $stamp`$1", 1)
$block = '(?s)<!-- SESSION_SNAPSHOT:BEGIN.*?SESSION_SNAPSHOT:END -->'
if ($ctx -match $block) {
    $ctx = [regex]::Replace($ctx, $block, { param($m) $snapshotText })
} else {
    $ctx = $ctx.TrimEnd() + "`r`n`r`n---`r`n`r`n" + $snapshotText + "`r`n"
}

# --- Learned advice candidates (Newest at top per RULE-CTX-005) ------------------
$learnFile = Join-Path $agentsDir 'LEARNED_ADVICE.md'
$learned = [System.IO.File]::ReadAllText($learnFile)
$added = 0
$newCandidateLines = [System.Collections.Generic.List[string]]::new()
foreach ($line in @($Learn | Where-Object { -not [string]::IsNullOrWhiteSpace($_) })) {
    if ($learned.Contains($line.Trim())) { continue }
    $newCandidateLines.Add("- [ ] $($line.Trim()) ($today, $Author)")
    $added++
}

if ($newCandidateLines.Count -gt 0) {
    $candPattern = '(?m)^## Candidates\s*\(pending review\)\s*$'
    if ($learned -match $candPattern) {
        $insertBlock = "`r`n" + ($newCandidateLines -join "`r`n")
        $learned = [regex]::Replace($learned, $candPattern, { param($m) "$($m.Value)$insertBlock" }, 1)
    } else {
        $learned = $learned.TrimEnd() + "`r`n`r`n## Candidates (pending review)`r`n" + ($newCandidateLines -join "`r`n") + "`r`n"
    }
}

if ($DryRun) {
    Write-Host "[DryRun] ACTIVE_CONTEXT.md would be stamped $today with $($rows.Count) repo row(s); $added learn candidate(s) would be added."
    return
}
[System.IO.File]::WriteAllText($contextFile, $ctx, $utf8)
[System.IO.File]::WriteAllText($learnFile, $learned, $utf8)

# --- ACTIVE_SESSION.md status update ------------------------------------------
$sessionFile = Join-Path $agentsDir 'ACTIVE_SESSION.md'
if (Test-Path -LiteralPath $sessionFile) {
    $sessContent = [System.IO.File]::ReadAllText($sessionFile)
    $sessContent = [regex]::Replace($sessContent, '(?m)^\- \*\*Last Updated\*\*:\s*.*$', "- **Last Updated**: $stamp", 1)
    if ($Quiescent) {
        if ($sessContent -match '(?m)^\- \*\*Status\*\*:\s*.*$') {
            $sessContent = [regex]::Replace($sessContent, '(?m)^\- \*\*Status\*\*:\s*.*$', "- **Status**: Quiescent (GoodNight completed at $stamp)", 1)
        } else {
            $sessContent = [regex]::Replace($sessContent, '(?m)^(\- \*\*Last Updated\*\*:\s*.*)$', "`$1`r`n- **Status**: Quiescent (GoodNight completed at $stamp)", 1)
        }
        if ($sessContent -match '(?m)^\- \*\*GoodNight Timestamp\*\*:\s*.*$') {
            $sessContent = [regex]::Replace($sessContent, '(?m)^\- \*\*GoodNight Timestamp\*\*:\s*.*$', "- **GoodNight Timestamp**: $stamp", 1)
        } else {
            $sessContent = [regex]::Replace($sessContent, '(?m)^(\- \*\*Status\*\*:\s*.*)$', "`$1`r`n- **GoodNight Timestamp**: $stamp", 1)
        }
    }
    [System.IO.File]::WriteAllText($sessionFile, $sessContent, $utf8)
}

Write-Host "  [OK] ACTIVE_CONTEXT.md stamped $today ($($rows.Count) repo row(s)); LEARNED_ADVICE.md +$added candidate(s)." -ForegroundColor Green
